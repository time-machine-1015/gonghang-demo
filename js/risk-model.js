  function features(text) {
    const t = String(text).toLowerCase().replace(/\s+/g, "");
    const out = {};
    const add = g => { out[g] = (out[g] || 0) + 1; };
    for (let n = 2; n <= 3; n++) {
      for (let i = 0; i + n <= t.length; i++) add(t.slice(i, i + n));
    }
    DOMAIN_KW.forEach(kw => { if (t.includes(kw)) add("KW:" + kw); });
    return out;
  }

  /* ---------- 训练:Multinomial NB(加一平滑) ---------- */
  function fit(samples) {
    const vocab = {};
    const cls = { 1: { n: 0, tf: {}, doc: 0 }, 0: { n: 0, tf: {}, doc: 0 } };
    samples.forEach(s => {
      cls[s.y].doc++;
      const f = features(s.t);
      for (const g in f) {
        vocab[g] = (vocab[g] || 0) + f[g];
        cls[s.y].tf[g] = (cls[s.y].tf[g] || 0) + f[g];
        cls[s.y].n += f[g];
      }
    });
    const V = Object.keys(vocab).length;
    const total = samples.length;
    const logprior = { 1: Math.log(cls[1].doc / total), 0: Math.log(cls[0].doc / total) };
    const loglike = { 1: {}, 0: {} };
    [1, 0].forEach(c => {
      for (const g in vocab) loglike[c][g] = Math.log((cls[c].tf[g] || 0) + 1) - Math.log(cls[c].n + V);
    });
    const unk = { 1: Math.log(1) - Math.log(cls[1].n + V), 0: Math.log(1) - Math.log(cls[0].n + V) };
    return { vocab: Object.keys(vocab), logprior, loglike, unk };
  }

  function predict(model, text) {
    const f = features(text);
    const lp = { 1: model.logprior[1], 0: model.logprior[0] };
    for (const g in f) {
      [1, 0].forEach(c => { lp[c] += (model.loglike[c][g] !== undefined ? model.loglike[c][g] : model.unk[c]) * f[g]; });
    }
    // 归一化后验概率(数值稳定:先减最大值)
    const m = Math.max(lp[1], lp[0]);
    const e1 = Math.exp(lp[1] - m), e0 = Math.exp(lp[0] - m);
    const p = e1 / (e1 + e0);
    // 可解释性:对预测类贡献最大的特征
    const top = Object.keys(f)
      .map(g => {
        const a = model.loglike[1][g] !== undefined ? model.loglike[1][g] : model.unk[1];
        const b = model.loglike[0][g] !== undefined ? model.loglike[0][g] : model.unk[0];
        return [g, (a - b) * f[g]];
      })
      .sort((x, y) => Math.abs(y[1]) - Math.abs(x[1]))
      .slice(0, 3)
      .map(([g, v]) => ({ g, v: +v.toFixed(2) }));
    return { label: p >= 0.5 ? "scam" : "normal", p: +p.toFixed(4), top };
  }

  /* ---------- 5 折交叉验证(结果可复现) ---------- */
  function crossValidate(k) {
    k = k || 5;
    let tp = 0, fp = 0, tn = 0, fn = 0;
    // 严格分组:验证集 = i%k===0,训练集 = 其余全部
    for (let i = 0; i < SAMPLES.length; i++) {
      if (i % k !== 0) continue;
      const trainSet = SAMPLES.filter((_, j) => j % k !== 0);
      const m = fit(trainSet);
      const r = predict(m, SAMPLES[i].t);
      const pred = r.label === "scam" ? 1 : 0;
      if (SAMPLES[i].y === 1 && pred === 1) tp++;
      else if (SAMPLES[i].y === 0 && pred === 1) fp++;
      else if (SAMPLES[i].y === 0 && pred === 0) tn++;
      else if (SAMPLES[i].y === 1 && pred === 0) fn++;
    }
    const acc = (tp + tn) / (tp + fp + tn + fn);
    const prec = tp + fp ? tp / (tp + fp) : 0;
    const rec = tp + fn ? tp / (tp + fn) : 0;
    const f1 = prec + rec ? (2 * prec * rec) / (prec + rec) : 0;
    return { tp, fp, tn, fn, acc, prec, rec, f1, k };
  }

